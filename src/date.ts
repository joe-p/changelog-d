const MONTHS = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
] as const;

function ordinal(day: number): string {
  if (day >= 11 && day <= 13) return "th";
  switch (day % 10) {
    case 1:
      return "st";
    case 2:
      return "nd";
    case 3:
      return "rd";
    default:
      return "th";
  }
}

export function formatReleaseDate(date: Date = new Date()): string {
  const day = date.getDate();
  return `${MONTHS[date.getMonth()]!} ${day}${ordinal(day)}, ${date.getFullYear()}`;
}
